<details class="wp-block-details"><summary>Les produits vendus sont-ils officiels&nbsp;?</summary><!-- wp:paragraph -->
<p>Oui. TCGForge vend des produits sous licence officielle, neufs. Les produits scellés sont livrés dans leur emballage d'origine. La page Authenticité des produits détaille nos engagements.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Comment fonctionne une précommande&nbsp;?</summary><!-- wp:paragraph -->
<p>Une précommande réserve un produit avant sa sortie. La fiche indique la date annoncée par l'éditeur. La commande est expédiée à la disponibilité du produit. Les conditions complètes figurent sur la page Fonctionnement des précommandes.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Quels sont les délais de livraison&nbsp;?</summary><!-- wp:paragraph -->
<p>Le délai dépend du produit et du transporteur choisi. Il est indiqué avant la validation de la commande et rappelé sur la page Livraison. Un e-mail avec le numéro de suivi part dès l'expédition.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Est-il possible de retourner un produit&nbsp;?</summary><!-- wp:paragraph -->
<p>Vous disposez de quatorze jours à compter de la réception pour exercer votre droit de rétractation sur les produits éligibles. La page Retours et remboursements décrit la marche à suivre.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Dans quelle langue sont les cartes&nbsp;?</summary><!-- wp:paragraph -->
<p>La langue figure sur chaque fiche produit et dans les filtres du catalogue. Vérifiez-la avant d'ajouter un produit au panier, un même produit existe souvent en plusieurs langues.</p>

<h2 class="wp-block-heading has-l-font-size">Ce qu'est un cookie</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Un cookie est un petit fichier déposé sur votre appareil lors de la consultation d'un site. Il permet de mémoriser une information : le fait que vous soyez connectée, votre choix en matière de traceurs, ou la manière dont vous naviguez.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"fontSize":"l"} -->
<h2 class="wp-block-heading has-l-font-size">Les cookies utilisés sur ce site</h2>
<!-- /wp:heading -->

<!-- wp:heading {"level":3,"fontSize":"m"} -->
<h3 class="wp-block-heading has-m-font-size">Strictement nécessaires — sans consentement</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Ces traceurs sont indispensables au fonctionnement du site. Ils sont dispensés de consentement au titre de l'article 82 de la loi Informatique et Libertés.</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>cmplz_*</strong> — mémorise votre choix en matière de cookies. Durée : 365 jours.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>wordpress_*, wp-settings-*</strong> — session et préférences d'administration, déposés uniquement si vous vous connectez à l'espace d'administration. Durée : session à 12 mois.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>Fluent Forms</strong> — jeton de sécurité anti-spam à la soumission d'un formulaire. Durée : session.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading {"level":3,"fontSize":"m"} -->
<h3 class="wp-block-heading has-m-font-size">Mesure d'audience — soumis à votre consentement</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Google Analytics 4, mis en œuvre via l'extension Google Site Kit, nous indique combien de personnes visitent le site et quelles pages les intéressent. Ces traceurs ne sont déposés qu'après votre acceptation.</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li><strong>_ga</strong> — distingue les visiteurs. Durée : 13 mois.</li>
<!-- /wp:list-item -->

<!-- wp:list-item -->
<li><strong>_ga_[identifiant]</strong> — maintient l'état de la session. Durée : 13 mois.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->


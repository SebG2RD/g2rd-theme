<div class="wp-block-group r18-ccs-faq"><!-- wp:details -->
<details class="wp-block-details"><summary>Où s’inscrire ?</summary><!-- wp:paragraph -->
<p>Sur <a href="https://www.concours-territorial.fr/">Concours-Territorial</a>, le portail des centres de gestion. Tu choisis un centre organisateur, tu crées ton compte, puis tu envoies ton dossier avant la date limite.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Réussir le concours donne-t-il un poste ?</summary><!-- wp:paragraph -->
<p>Non. Le concours t’inscrit sur une liste d’aptitude. Tu candidates ensuite auprès des SDIS qui recrutent : consulte les <a href="/recrutement/offres-emploi/">offres d’emploi des SDIS</a>.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Je suis sapeur-pompier volontaire : quelle voie ?</summary><!-- wp:paragraph -->
<p>Le concours de caporal compte une voie réservée aux volontaires qui justifient de trois ans d’activité et de leur formation initiale. Les conditions exactes figurent sur la fiche du concours.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>Et la BSPP ou le BMPM ?</summary><!-- wp:paragraph -->
<p>Ces deux unités sont militaires. Elles recrutent par engagement, sans concours de la fonction publique territoriale. Toutes les voies sont sur la page <a href="/devenir-pompier/">Devenir sapeur-pompier</a>.</p>
<!-- /wp:paragraph --></details>
<!-- /wp:details -->
<!-- wp:details -->
<details class="wp-block-details"><summary>D’où viennent les dates ?</summary><!-- wp:paragraph -->
<p>De Concours-Territorial, relevé chaque matin, et des annonces des SDIS. Seul l’arrêté d’ouverture du centre organisateur fait foi : vérifie-le avant de t’inscrire.</p>

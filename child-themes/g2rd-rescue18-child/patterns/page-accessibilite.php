<section class="wp-block-group" style="padding-top:var(--wp--preset--spacing--60);padding-bottom:var(--wp--preset--spacing--70)"><!-- wp:paragraph -->
<p>Cette déclaration s'applique au site rescue18.com.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">État de conformité</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Le site n'a pas encore fait l'objet d'un audit complet. Il est donc déclaré <strong>non conforme</strong> au RGAA 4.1 en attendant les résultats de cet audit.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Mesures prises dès la refonte</h2>
<!-- /wp:heading -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Contrastes des textes et des éléments d'interface vérifiés (4,5:1 pour les textes courants, 3:1 pour les grands titres et les bordures de champs).</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Navigation complète au clavier, lien d'évitement vers le contenu, focus visible.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Titres hiérarchisés, zones de page balisées, fil d'Ariane.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Animations coupées avec le réglage « réduire les animations » du système.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Textes alternatifs pour les images porteuses d'information. Icônes décoratives ignorées par les lecteurs d'écran.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Contenus non accessibles connus</h2>
<!-- /wp:heading -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Certains documents PDF proviennent d'organismes officiels (DGSCGC, ENSOSP). Leur accessibilité dépend de ces organismes. Rescue 18 renvoie vers la publication d'origine.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Les vidéos YouTube du podcast ne disposent pas toutes de sous-titres vérifiés.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Établissement de cette déclaration</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Déclaration établie à la mise en ligne de la nouvelle version du site. Technologies utilisées : HTML5, CSS, JavaScript, WordPress.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Retour d'information et contact</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Un contenu ou un service vous est inaccessible ? Écrivez-nous via la <a href="/contactez-nous/">page Contact</a>. Nous vous proposerons une alternative accessible ou le contenu sous une autre forme.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Voies de recours</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->

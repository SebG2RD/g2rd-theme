<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>un délégué du Défenseur des droits dans votre région,</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>un courrier gratuit, sans timbre : Défenseur des droits, Libre réponse 71120, 75342 Paris CEDEX 07.</li>

<p class="r18-lex-def__ex">DRAGON · LANCELOT · MERLIN</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">L’indicatif radio</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Un nom choisi, pas formé d’initiales. Il désigne un engin ou une fonction sur les ondes.</p>

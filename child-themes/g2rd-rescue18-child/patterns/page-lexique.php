<h3 class="wp-block-heading">L’emprunt à l’anglais</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Un terme anglais gardé tel quel, sigle ou mot, faute d’équivalent aussi court en français.</p>

<h2 class="wp-block-heading r18-h2">Sigle, acronyme ou abréviation ?</h2>
<!-- /wp:heading --></div>
<!-- /wp:group --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"r18-lex-def","layout":{"type":"default"}} -->
<div class="wp-block-group r18-lex-def"><!-- wp:group {"className":"r18-lex-def__card","layout":{"type":"default"}} -->
<div class="wp-block-group r18-lex-def__card"><!-- wp:paragraph {"className":"r18-lex-def__ex"} -->
<p class="r18-lex-def__ex">VSAV · FPT · CTA</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Le sigle</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Une suite d’initiales lue lettre par lettre. Il s’écrit en capitales, sans point, sans espace et sans trait d’union.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"r18-lex-def__card","layout":{"type":"default"}} -->
<div class="wp-block-group r18-lex-def__card"><!-- wp:paragraph {"className":"r18-lex-def__ex"} -->
<p class="r18-lex-def__ex">CODIS · ORSEC · GRIMP</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">L’acronyme</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Un sigle prononcé comme un mot ordinaire : on dit « codisse », « orsec », « grimpe ».</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"r18-lex-def__card","layout":{"type":"default"}} -->
<div class="wp-block-group r18-lex-def__card"><!-- wp:paragraph {"className":"r18-lex-def__ex"} -->
<p class="r18-lex-def__ex">SDIS · SSSM</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Le sigle mixte</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>On épelle une partie et on prononce le reste : « esse-dis », « trois-esse-emme ».</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"r18-lex-def__card","layout":{"type":"default"}} -->
<div class="wp-block-group r18-lex-def__card"><!-- wp:paragraph {"className":"r18-lex-def__ex"} -->
<p class="r18-lex-def__ex">CNE · LTN · CYN</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">L’abréviation</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Un mot raccourci : les lettres viennent du mot entier, pas d’initiales. C’est la règle des grades et des spécialités.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"r18-lex-def__card","layout":{"type":"default"}} -->
<div class="wp-block-group r18-lex-def__card"><!-- wp:paragraph {"className":"r18-lex-def__ex"} -->
<p class="r18-lex-def__ex">TOOTEM · RAPACE</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Le moyen mnémotechnique</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Un mot formé pour retenir une procédure dans l’ordre : chaque lettre donne une étape à vérifier.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"r18-lex-def__card","layout":{"type":"default"}} -->
<div class="wp-block-group r18-lex-def__card"><!-- wp:paragraph {"className":"r18-lex-def__ex"} -->
<p class="r18-lex-def__ex">F1 · F2 · U1</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Le code</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Une lettre et un chiffre pour classer : une tenue de feu, un niveau d’urgence.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"className":"r18-lex-def__card","layout":{"type":"default"}} -->
<div class="wp-block-group r18-lex-def__card"><!-- wp:paragraph {"className":"r18-lex-def__ex"} -->
<p class="r18-lex-def__ex">VSAB → VSAV · CIRCOSC → COZ</p>
<!-- /wp:paragraph -->
<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">L’ancien sigle</h3>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>Un sigle remplacé quand l’engin ou le service change de nom. Il reste dans les anciens textes et dans le langage de caserne.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
